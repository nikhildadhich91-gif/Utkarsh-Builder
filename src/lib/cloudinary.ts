export const getOptimizedImageUrl = (url: string, width: number) => {
  if (!url) return '';
  if (!url.includes('cloudinary.com')) return url;
  
  // If it already has f_auto,q_auto, replace or append width
  if (url.includes('/image/upload/f_auto,q_auto')) {
    return url.replace('/image/upload/f_auto,q_auto', `/image/upload/f_auto,q_auto,w_${width}`);
  }
  
  // Otherwise, insert f_auto,q_auto,w_${width} right after /image/upload/
  return url.replace('/image/upload/', `/image/upload/f_auto,q_auto,w_${width}/`);
};
